"""
build_station_scene.py -- builds the "Bharatiya Antariksh Station" (Indian space station) look-alike scene.

    .\\.venv\\Scripts\\python.exe build_station_scene.py

Reads  mujoco_menagerie/franka_emika_panda/panda_pick_place_marker.xml   (left untouched)
Writes mujoco_menagerie/franka_emika_panda/panda_station_marker.xml      (new scene)
       mujoco_menagerie/franka_emika_panda/station_assets/*.png          (generated textures)

Only the surroundings change: robot, table, red cube, yellow marker, physics and the camera are identical
to the marker scene, so every script (recorder, expert, evaluator) works on it unchanged.
All decoration is visual only (no collisions). Gravity stays normal (1 g).
The station is a module corner: floor, two walls, ribs, handrails, hatch, porthole to Earth, flag banner,
mission title panel (English + Devanagari), equipment rack with status lights.
Cube is red and marker yellow, so no red/yellow/saffron decoration is placed near the table.
"""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont
import math

ROOT = Path(__file__).resolve().parent
DIR = ROOT / "mujoco_menagerie" / "franka_emika_panda"
SRC = DIR / "panda_pick_place_marker.xml"
DST = DIR / "panda_station_marker.xml"
TEX = DIR / "station_assets"

SAFFRON, WHITE, GREEN, NAVY = (255, 153, 51), (255, 255, 255), (19, 136, 8), (0, 0, 128)


def font(path, size):
    try:
        return ImageFont.truetype(path, size)
    except OSError:
        return ImageFont.load_default()


def make_banner(path):
    """Indian tricolour (saffron / white / green) with a 24-spoke navy Ashoka chakra."""
    w, h = 1024, 512
    im = Image.new("RGB", (w, h), WHITE)
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, w, h // 3], fill=SAFFRON)
    d.rectangle([0, 2 * h // 3, w, h], fill=GREEN)
    cx, cy, r = w // 2, h // 2, h // 6 - 4
    d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=NAVY, width=5)
    for k in range(24):
        a = 2 * math.pi * k / 24
        d.line([cx, cy, cx + r * math.cos(a), cy + r * math.sin(a)], fill=NAVY, width=2)
    im.save(path)


def make_title(path):
    w, h = 1024, 256
    im = Image.new("RGB", (w, h), (12, 22, 48))
    d = ImageDraw.Draw(im)
    d.rectangle([0, 0, w, 10], fill=SAFFRON)
    d.rectangle([0, h - 10, w, h], fill=GREEN)
    f1 = font("C:/Windows/Fonts/arialbd.ttf", 50)
    f2 = font("C:/Windows/Fonts/Nirmala.ttc", 62)
    for text, f, y in [("BHARATIYA ANTARIKSH STATION", f1, 40), ("\u092d\u093e\u0930\u0924\u0940\u092f \u0905\u0902\u0924\u0930\u093f\u0915\u094d\u0937 \u0938\u094d\u091f\u0947\u0936\u0928", f2, 135)]:
        tw = d.textlength(text, font=f)
        d.text(((w - tw) / 2, y), text, font=f, fill=(235, 240, 250))
    im.save(path)


def make_earth(path):
    """Simple Earth-from-orbit picture for the porthole: blue ocean, green-brown land, white cloud, dark space."""
    import random
    random.seed(7)
    s = 512
    im = Image.new("RGB", (s, s), (3, 6, 18))
    d = ImageDraw.Draw(im)
    for _ in range(120):
        x, y = random.randrange(s), random.randrange(s)
        d.point((x, y), fill=(255, 255, 255))
    R = int(s * 0.95)
    cx, cy = s // 2, int(s * 1.05)
    d.ellipse([cx - R, cy - R, cx + R, cy + R], fill=(24, 82, 170))
    for _ in range(14):
        x, y = random.randrange(40, s - 40), random.randrange(int(s * 0.45), s)
        rr = random.randrange(18, 55)
        d.ellipse([x - rr, y - rr // 2, x + rr, y + rr // 2], fill=(60, 120, 60))
    for _ in range(22):
        x, y = random.randrange(20, s - 20), random.randrange(int(s * 0.4), s)
        d.ellipse([x - 40, y - 8, x + 40, y + 8], fill=(235, 240, 250))
    d.arc([cx - R - 6, cy - R - 6, cx + R + 6, cy + R + 6], 200, 340, fill=(120, 190, 255), width=8)
    im.save(path)


def main():
    TEX.mkdir(exist_ok=True)
    make_banner(TEX / "banner.png")
    make_title(TEX / "title.png")
    make_earth(TEX / "earth.png")

    xml = SRC.read_text()

    # --- compiler: where textures live; visual: brighter ambient so the module looks like a lit interior ---
    xml = xml.replace('<compiler angle="radian" meshdir="assets" autolimits="true"/>',
                      '<compiler angle="radian" meshdir="assets" texturedir="station_assets" autolimits="true"/>\n'
                      '  <visual><headlight ambient="0.35 0.37 0.42" diffuse="0.55 0.55 0.6" specular="0.1 0.1 0.1"/>'
                      '<global offwidth="640" offheight="480"/></visual>')

    assets = """
    <!-- ===== Space-station look (generated by build_station_scene.py) ===== -->
    <texture name="floor_tex" type="2d" builtin="checker" rgb1="0.30 0.33 0.38" rgb2="0.24 0.27 0.32"
             width="512" height="512" mark="edge" markrgb="0.55 0.6 0.66"/>
    <texture name="wall_tex" type="2d" builtin="checker" rgb1="0.78 0.80 0.84" rgb2="0.72 0.74 0.79"
             width="512" height="512" mark="edge" markrgb="0.45 0.48 0.55"/>
    <texture name="banner_tex" type="2d" file="banner.png"/>
    <texture name="title_tex" type="2d" file="title.png"/>
    <texture name="earth_tex" type="2d" file="earth.png"/>
    <material name="floor_mat" texture="floor_tex" texrepeat="6 6" texuniform="true" specular="0.2" reflectance="0.1"/>
    <material name="wall_mat" texture="wall_tex" texrepeat="2 2" texuniform="true" specular="0.2"/>
    <material name="banner_mat" texture="banner_tex" emission="0.35" specular="0"/>
    <material name="title_mat" texture="title_tex" emission="0.5" specular="0"/>
    <material name="earth_mat" texture="earth_tex" emission="0.8" specular="0"/>
    <material name="rib_mat" rgba="0.55 0.58 0.64 1" specular="0.5" shininess="0.4"/>
    <material name="rail_mat" rgba="0.15 0.45 0.85 1" specular="0.6" shininess="0.5"/>
    <material name="rack_mat" rgba="0.20 0.22 0.27 1" specular="0.4"/>
    <material name="led_green" rgba="0.1 1.0 0.3 1" emission="1" specular="0"/>
    <material name="led_blue" rgba="0.2 0.6 1.0 1" emission="1" specular="0"/>
    <material name="frame_mat" rgba="0.6 0.62 0.68 1" specular="0.6" shininess="0.6"/>
"""
    xml = xml.replace("    <!-- Collision meshes -->", assets + "\n    <!-- Collision meshes -->", 1)

    # --- floor: same plane/friction, station material ---
    old_ground = '''<geom name="ground"
          type="plane"
          pos="0 0 0"
          size="2 2 0.1"
          rgba="0.75 0.75 0.75 1"
          friction="1.0 0.02 0.002"/>'''
    assert old_ground in xml
    xml = xml.replace(old_ground, '''<geom name="ground" type="plane" pos="0 0 0" size="3 3 0.1"
          material="floor_mat" friction="1.0 0.02 0.002"/>''')

    deco = []
    A = deco.append
    NC = 'contype="0" conaffinity="0"'
    # walls (visual only): back wall y=+1.3 (faces -y), side wall x=-0.9 (faces +x)
    A(f'<geom name="st_wall_back" type="box" pos="0.8 1.32 1.3" size="1.8 0.02 1.3" material="wall_mat" {NC}/>')
    A(f'<geom name="st_wall_side" type="box" pos="-0.92 -0.1 1.3" size="0.02 1.45 1.3" material="wall_mat" {NC}/>')
    # vertical ribs and horizontal rails
    for i, x in enumerate([-0.5, 0.3, 1.1, 1.9]):
        A(f'<geom name="st_rib_b{i}" type="box" pos="{x} 1.285 1.3" size="0.05 0.025 1.3" material="rib_mat" {NC}/>')
    for i, y in enumerate([-1.0, -0.3, 0.4, 1.0]):
        A(f'<geom name="st_rib_s{i}" type="box" pos="-0.885 {y} 1.3" size="0.025 0.05 1.3" material="rib_mat" {NC}/>')
    for i, z in enumerate([0.15, 2.45]):
        A(f'<geom name="st_belt_b{i}" type="box" pos="0.8 1.28 {z}" size="1.8 0.03 0.06" material="rib_mat" {NC}/>')
        A(f'<geom name="st_belt_s{i}" type="box" pos="-0.88 -0.1 {z}" size="0.03 1.45 0.06" material="rib_mat" {NC}/>')
    # handrails (blue) on both walls, stand-off posts included
    A(f'<geom name="st_rail_b" type="capsule" fromto="-0.7 1.2 0.95 2.4 1.2 0.95" size="0.022" material="rail_mat" {NC}/>')
    A(f'<geom name="st_rail_s" type="capsule" fromto="-0.8 -1.4 0.95 -0.8 1.2 0.95" size="0.022" material="rail_mat" {NC}/>')
    for i, x in enumerate([-0.5, 0.3, 1.1, 1.9]):
        A(f'<geom name="st_post_b{i}" type="capsule" fromto="{x} 1.28 0.95 {x} 1.2 0.95" size="0.015" material="rail_mat" {NC}/>')
    for i, y in enumerate([-1.0, -0.3, 0.4]):
        A(f'<geom name="st_post_s{i}" type="capsule" fromto="-0.88 {y} 0.95 -0.8 {y} 0.95" size="0.015" material="rail_mat" {NC}/>')
    # banner (tricolour + chakra) on the side wall, title panel on the back wall
    A(f'<geom name="st_banner" type="plane" pos="-0.83 0.15 1.65" size="0.45 0.30 0.01" '
      f'xyaxes="0 1 0 0 0 1" material="banner_mat" {NC}/>')
    A(f'<geom name="st_banner_frame" type="box" pos="-0.845 0.15 1.65" size="0.005 0.47 0.32" material="frame_mat" {NC}/>')
    A(f'<geom name="st_title" type="plane" pos="0.9 1.24 1.95" size="0.7 0.175 0.01" '
      f'xyaxes="1 0 0 0 0 1" material="title_mat" {NC}/>')
    # porthole to Earth on the back wall: metal ring + picture
    A(f'<geom name="st_port_ring" type="cylinder" pos="0.0 1.245 1.45" euler="1.5708 0 0" size="0.36 0.02" material="frame_mat" {NC}/>')
    A(f'<geom name="st_port_view" type="plane" pos="0.0 1.223 1.45" size="0.25 0.25 0.01" '
      f'xyaxes="1 0 0 0 0 1" material="earth_mat" {NC}/>')
    # round hatch on the side wall (low, far from the table)
    A(f'<geom name="st_hatch_ring" type="cylinder" pos="-0.89 -0.8 1.0" euler="0 1.5708 0" size="0.30 0.02" material="frame_mat" {NC}/>')
    A(f'<geom name="st_hatch_door" type="cylinder" pos="-0.87 -0.8 1.0" euler="0 1.5708 0" size="0.25 0.02" material="rib_mat" {NC}/>')
    A(f'<geom name="st_hatch_wheel" type="cylinder" pos="-0.85 -0.8 1.0" euler="0 1.5708 0" size="0.07 0.015" material="rail_mat" {NC}/>')
    # equipment rack with status lights (back wall, right of porthole)
    A(f'<geom name="st_rack" type="box" pos="1.55 1.15 0.7" size="0.35 0.12 0.7" material="rack_mat" {NC}/>')
    for r in range(6):
        for c in range(4):
            m = "led_green" if (r + c) % 3 else "led_blue"
            A(f'<geom name="st_led_{r}_{c}" type="sphere" pos="{1.30 + 0.16 * c} 1.025 {0.25 + 0.2 * r}" size="0.014" material="{m}" {NC}/>')
    # floor strips marking the work area under the table
    A(f'<geom name="st_floor_strip" type="box" pos="0.55 0.0 0.002" size="0.55 0.65 0.002" rgba="0.18 0.20 0.25 1" {NC}/>')

    block = "\n    <!-- ===== Space-station decoration (visual only) ===== -->\n    " + "\n    ".join(deco) + "\n"
    xml = xml.replace("</worldbody>", block + "\n</worldbody>", 1)
    xml = xml.replace('<mujoco model="panda">', '<mujoco model="panda_station">', 1)
    DST.write_text(xml)
    print("wrote", DST)


if __name__ == "__main__":
    main()
