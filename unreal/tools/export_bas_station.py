"""Convert BAS module box geometry into compact Unreal C++ instance data.

Run from any directory: python3 unreal/tools/export_bas_station.py
The checked-in .inl is generated from bas_lab/mod_bas_module.xml with only
Python's standard library. Positions are centimetres in Unreal's X/-Y/Z basis.
"""

from __future__ import annotations

import math
from pathlib import Path
import xml.etree.ElementTree as ET


ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "bas_lab/mod_bas_module.xml"
OUTPUT = ROOT / "unreal/BASPanda/Source/BASPanda/StationModuleBoxes.inl"

MATERIALS = (
    "rack_body", "locker_a", "locker_b", "locker_c", "dark",
    "accent_teal", "accent_blue", "screen", "screen_dim", "frame_mat",
    "led_green", "led_blue", "led_white",
)


def vec(text: str, count: int) -> tuple[float, ...]:
    result = tuple(float(part) for part in text.split())
    if len(result) != count:
        raise ValueError(f"expected {count} values, got {text!r}")
    return result


def rotate(q: tuple[float, ...], v: tuple[float, ...]) -> tuple[float, ...]:
    w, x, y, z = q
    vx, vy, vz = v
    tx, ty, tz = (2 * (y * vz - z * vy),
                  2 * (z * vx - x * vz),
                  2 * (x * vy - y * vx))
    return (vx + w * tx + y * tz - z * ty,
            vy + w * ty + z * tx - x * tz,
            vz + w * tz + x * ty - y * tx)


def emit_box(geom: ET.Element, body: ET.Element | None) -> str:
    name = geom.attrib["name"]
    material = geom.attrib["material"]
    if material not in MATERIALS:
        raise ValueError(f"unknown box material {material} on {name}")
    local = vec(geom.attrib["pos"], 3)
    size = vec(geom.attrib["size"], 3)
    if body is None:
        body_pos = (0.0, 0.0, 0.0)
        body_q = (1.0, 0.0, 0.0, 0.0)
    else:
        body_pos = vec(body.attrib["pos"], 3)
        body_q = vec(body.attrib.get("quat", "1 0 0 0"), 4)
    length = math.sqrt(sum(value * value for value in body_q))
    body_q = tuple(value / length for value in body_q)
    rotated = rotate(body_q, local)
    world = tuple(body_pos[i] + rotated[i] for i in range(3))

    # Reflection across Y: positions (x,-y,z), axial quaternion (-x,y,-z).
    p = (100 * world[0], -100 * world[1], 100 * world[2])
    q = (-body_q[1], body_q[2], -body_q[3], body_q[0])
    scale = tuple(2 * value for value in size)  # Engine cube has 100 cm sides.
    numbers = (*p, *q, *scale)
    if not all(math.isfinite(value) for value in numbers):
        raise ValueError(f"nonfinite transform on {name}")
    fmt = lambda value: f"{value:.6f}f"
    return (f"    {{FVector({', '.join(map(fmt, p))}), "
            f"FQuat({', '.join(map(fmt, q))}), "
            f"FVector({', '.join(map(fmt, scale))}), "
            f"{MATERIALS.index(material)}}}, // {name}")


def main() -> None:
    world = ET.parse(SOURCE).getroot().find("worldbody")
    if world is None:
        raise ValueError("BAS module has no worldbody")
    lines = []
    for geom in world.findall("geom"):
        if geom.attrib.get("type") == "box" and not geom.attrib["name"].startswith("shell_"):
            lines.append(emit_box(geom, None))
    racks = 0
    for body in world.findall("body"):
        if body.attrib.get("name", "").startswith("rk"):
            racks += 1
        for geom in body.findall("geom"):
            if geom.attrib.get("type") == "box":
                lines.append(emit_box(geom, body))
    if racks != 77 or len(lines) != 1350:
        raise ValueError(f"source geometry changed: {racks} racks, {len(lines)} boxes")
    header = ("// Generated by unreal/tools/export_bas_station.py from bas_lab/mod_bas_module.xml.\n"
              "// Material indices match StationMaterialColors in BASStationModuleActor.cpp.\n"
              "static const FStationBox GStationBoxes[] = {\n")
    OUTPUT.write_text(header + "\n".join(lines) + "\n};\n")
    print(f"Wrote {len(lines)} boxes from {racks} racks to {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
